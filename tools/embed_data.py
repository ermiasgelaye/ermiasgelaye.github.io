#!/usr/bin/env python3
"""Embed project CSVs as JavaScript so the pages also work when opened from disk (file://),
where browsers block fetch(). Run after editing a CSV:  python3 tools/embed_data.py
The CSV files remain the source of truth and the download links."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = ['Web-Design-Challenge/Resources/cities.csv', 'Matplotlib-Challenge/Resources/mouse_metadata.csv']
for rel in FILES:
    src = ROOT / rel
    out = src.with_suffix('.data.js')
    out.write_text('/* Generated by tools/embed_data.py from ' + src.name + ' — do not edit by hand. */\n'
                   'window.ARC_DATA = window.ARC_DATA || {};\n'
                   f'window.ARC_DATA[{json.dumps(src.name)}] = {json.dumps(src.read_text())};\n')
    print(f'{out.relative_to(ROOT)}  ({out.stat().st_size // 1024} KB)')
